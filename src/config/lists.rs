//! The lists the boost relies on: which apps and services may be touched, which programs are never "the game".

use super::*;

/// Show known programs, but never touch someone else's running apps before they choose an action.
/// Suggestions remain available in the catalog for an explicit opt-in.
pub fn default_apps() -> BTreeMap<String, ProcAction> {
    crate::catalog::KNOWN_APPS.iter().map(|a| (a.exe.to_string(), ProcAction::Keep)).collect()
}

